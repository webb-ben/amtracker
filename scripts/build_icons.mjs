// Write favicon.svg from the still frame of the app icon (src/icon.js), for browsers and places
// that show the static file before the page's script animates the tab icon.
//   npm run icons

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ICON_SIZE, iconGrid, iconColor } from "../src/icon.js";

const out = fileURLToPath(new URL("../favicon.svg", import.meta.url));

// One rect per horizontal run of a colour keeps the file small.
const rects = [];
iconGrid(0).forEach((row, y) => {
  for (let x = 0; x < ICON_SIZE; ) {
    let end = x + 1;
    while (end < ICON_SIZE && row[end] === row[x]) end++;
    rects.push(`<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${iconColor(row[x])}"/>`);
    x = end;
  }
});

writeFileSync(
  out,
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${ICON_SIZE} ${ICON_SIZE}" shape-rendering="crispEdges">
  <!-- Generated by scripts/build_icons.mjs from src/icon.js; don't edit by hand. -->
  <defs><clipPath id="r"><rect width="${ICON_SIZE}" height="${ICON_SIZE}" rx="4"/></clipPath></defs>
  <g clip-path="url(#r)">
    ${rects.join("\n    ")}
  </g>
</svg>
`,
);
console.log(`${rects.length} rects -> ${out}`);
