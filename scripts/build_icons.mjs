// Write favicon.svg from the head-on still of the favicon (src/icon.js), for browsers and places
// that show the static file before the page's script animates the tab icon, and the same still as
// PNG home-screen icons (iOS won't take an SVG apple-touch-icon; the web manifest uses the rest).
//   npm run icons

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { crc32, deflateSync } from "node:zlib";
import { ICON_SIZE, faviconGrid, iconColor } from "../src/icon.js";

const path = (name) => fileURLToPath(new URL(`../${name}`, import.meta.url));
const grid = faviconGrid();

// One rect per horizontal run of a colour keeps the file small.
const rects = [];
grid.forEach((row, y) => {
  for (let x = 0; x < ICON_SIZE; ) {
    let end = x + 1;
    while (end < ICON_SIZE && row[end] === row[x]) end++;
    rects.push(`<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${iconColor(row[x])}"/>`);
    x = end;
  }
});

writeFileSync(
  path("favicon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${ICON_SIZE} ${ICON_SIZE}" shape-rendering="crispEdges">
  <!-- Generated by scripts/build_icons.mjs from src/icon.js; don't edit by hand. -->
  <defs><clipPath id="r"><rect width="${ICON_SIZE}" height="${ICON_SIZE}" rx="4"/></clipPath></defs>
  <g clip-path="url(#r)">
    ${rects.join("\n    ")}
  </g>
</svg>
`,
);
console.log(`${rects.length} rects -> favicon.svg`);

// Home-screen icons are square and full bleed: the OS rounds the corners itself.
const HOME_ICONS = { "apple-touch-icon.png": 180, "icon-192.png": 192, "icon-512.png": 512 };

function chunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length);
  head.write(type, 4);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])));
  return Buffer.concat([head, data, crc]);
}

/** An RGB PNG of the grid, each art pixel blown up nearest-neighbour to fill `size`. */
function png(size) {
  const raw = Buffer.alloc(size * (1 + size * 3));
  for (let y = 0; y < size; y++) {
    const row = grid[Math.floor((y * ICON_SIZE) / size)];
    const at = y * (1 + size * 3); // each scanline starts with filter type 0
    for (let x = 0; x < size; x++) {
      const hex = iconColor(row[Math.floor((x * ICON_SIZE) / size)]);
      for (let i = 0; i < 3; i++) raw[at + 1 + x * 3 + i] = parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16);
    }
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header[8] = 8; // bit depth
  header[9] = 2; // truecolour
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

for (const [name, size] of Object.entries(HOME_ICONS)) {
  writeFileSync(path(name), png(size));
  console.log(`${size}px -> ${name}`);
}
